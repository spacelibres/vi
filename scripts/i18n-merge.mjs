import fs from 'node:fs';
import path from 'node:path';

// 合并 i18n/*.json（zh-CN.json 为源语言基准，不参与合并）为可离线加载的 i18n-data.js。
export function locales() {
  return fs.readdirSync('i18n')
    .filter((f) => f.endsWith('.json') && f !== 'zh-CN.json')
    .map((f) => f.replace(/\.json$/, ''))
    .sort();
}

export function build() {
  const out = {};
  for (const locale of locales()) {
    out[locale] = JSON.parse(fs.readFileSync(path.join('i18n', locale + '.json'), 'utf8'));
  }
  return '/* Generated by scripts/build-i18n.mjs - do not edit. */\n'
    + 'window.SPACELIBRE_I18N = ' + JSON.stringify(out) + ';\n';
}
